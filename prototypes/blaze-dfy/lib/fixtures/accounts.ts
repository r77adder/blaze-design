function phases(current: PhaseId, status: 'not_started' | 'in_progress' | 'complete'): PhaseProgress[] {
  const names: Record<PhaseId, string> = {
    1: 'Registration',
    2: 'Strategy',
    3: 'Creative Review',
  };
  return ([1, 2, 3] as PhaseId[]).map((id) => ({
    id,
    name: names[id],
    status:
      id < current ? 'complete' : id > current ? 'not_started' : status,
  }));
}

